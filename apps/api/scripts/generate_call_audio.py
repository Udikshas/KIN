"""Generate the landing page "Hear tonight's call" audio, once.

Reads the lines from apps/web/src/components/landing/call-scripts.ts, voices
each one with Sarvam TTS (Kin and the parent get different voices), joins them
into one MP3 per language with short pauses, and writes:

    apps/web/public/audio/call-{hi,ta,en}.mp3
    apps/web/src/components/landing/call-audio.ts   (start time of each line)

The site only serves these static files, so playing the demo costs nothing.
Re-run only when the script text changes:

    .venv/bin/python scripts/generate_call_audio.py [hi ta en]

Needs SARVAM_API_KEY in apps/api/.env and ffmpeg on PATH.
"""

import base64
import json
import os
import re
import subprocess
import sys
import tempfile
from pathlib import Path

from sarvamai import SarvamAI

API = Path(__file__).resolve().parents[1]
WEB = API.parent / "web"
SCRIPTS_TS = WEB / "src/components/landing/call-scripts.ts"
OUT_AUDIO = WEB / "public/audio"
OUT_CUES = WEB / "src/components/landing/call-audio.ts"

# language code, Kin's voice, the parent's voice; each voice is (speaker, model).
# bulbul:v4-flash has only male Tamil voices, so Tamil uses v3's multilingual ones.
V4, V3 = "bulbul:v4-flash", "bulbul:v3"
VOICES = {
    "hi": ("hi-IN", ("roopa_hi_companion", V4), ("shreya_hi_conversational", V4)),
    "ta": ("ta-IN", ("roopa", V3), ("kavitha", V3)),
    "en": ("en-IN", ("roopa_en_conversational", V4), ("girish_en_documentary", V4)),
}
SAMPLE_RATE = 24000
GAP_S = 0.55  # pause between turns
LEAD_S = 0.3  # silence before the first line


def load_env() -> None:
    env = API / ".env"
    if env.exists():
        for line in env.read_text().splitlines():
            if "=" in line and not line.lstrip().startswith("#"):
                k, v = line.split("=", 1)
                os.environ.setdefault(k.strip(), v.strip())


def read_lines() -> dict[str, list[tuple[str, str]]]:
    """Returns {"hi": [(speaker, text), ...], ...} from call-scripts.ts."""
    src = SCRIPTS_TS.read_text()
    blocks = re.split(r'\n\s*id: "', src)[1:]
    out = {}
    for block in blocks:
        lang = block[:2]
        out[lang] = re.findall(r'speaker: "(kin|parent)", said: "([^"]+)"', block)
    return out


def tts(client: SarvamAI, text: str, lang: str, voice: tuple[str, str], path: Path) -> None:
    speaker, model = voice
    res = client.text_to_speech.convert(
        text=text,
        language_code=lang,
        speaker=speaker,
        model=model,
        speech_sample_rate=SAMPLE_RATE,
        output_audio_codec="wav",
        pace=0.95,
    )
    path.write_bytes(b"".join(base64.b64decode(a) for a in res.audios))


def duration(path: Path) -> float:
    out = subprocess.run(
        ["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", str(path)],
        capture_output=True, text=True, check=True,
    )
    return float(out.stdout.strip())


def silence(path: Path, seconds: float) -> None:
    subprocess.run(
        ["ffmpeg", "-y", "-v", "error", "-f", "lavfi", "-i", f"anullsrc=r={SAMPLE_RATE}:cl=mono",
         "-t", f"{seconds}", "-c:a", "pcm_s16le", str(path)],
        check=True,
    )


def build(client: SarvamAI, lang: str, lines: list[tuple[str, str]], tmp: Path) -> list[float]:
    code, kin_voice, parent_voice = VOICES[lang]
    lead, gap = tmp / "lead.wav", tmp / "gap.wav"
    silence(lead, LEAD_S)
    silence(gap, GAP_S)

    parts, cues, t = [lead], [], LEAD_S
    for i, (speaker, text) in enumerate(lines):
        wav = tmp / f"{lang}-{i}.wav"
        tts(client, text, code, kin_voice if speaker == "kin" else parent_voice, wav)
        # Normalise every clip to the same format so concat can copy streams.
        norm = tmp / f"{lang}-{i}-n.wav"
        subprocess.run(["ffmpeg", "-y", "-v", "error", "-i", str(wav), "-ar", str(SAMPLE_RATE),
                        "-ac", "1", "-c:a", "pcm_s16le", str(norm)], check=True)
        cues.append(round(t, 2))
        t += duration(norm) + GAP_S
        parts += [norm, gap]
        print(f"  {lang} {i + 1}/{len(lines)} {speaker:6} {duration(norm):.1f}s")

    listing = tmp / f"{lang}.txt"
    listing.write_text("".join(f"file '{p}'\n" for p in parts))
    OUT_AUDIO.mkdir(parents=True, exist_ok=True)
    subprocess.run(["ffmpeg", "-y", "-v", "error", "-f", "concat", "-safe", "0", "-i", str(listing),
                    "-c:a", "libmp3lame", "-b:a", "64k", "-ac", "1", str(OUT_AUDIO / f"call-{lang}.mp3")],
                   check=True)
    return cues


def write_cues(cues: dict[str, list[float]]) -> None:
    existing = {}
    if OUT_CUES.exists():
        m = re.search(r"= (\{.*\});", OUT_CUES.read_text(), re.S)
        if m:
            existing = json.loads(m.group(1))
    existing.update(cues)
    OUT_CUES.write_text(
        "// Generated by apps/api/scripts/generate_call_audio.py. Do not edit by hand.\n"
        "// Start time (seconds) of each line in public/audio/call-<id>.mp3.\n"
        f"export const callAudioCues: Record<string, number[]> = {json.dumps(existing, indent=2)};\n"
    )


def main() -> None:
    load_env()
    key = os.environ.get("SARVAM_API_KEY")
    if not key:
        sys.exit("SARVAM_API_KEY is empty in apps/api/.env")
    client = SarvamAI(api_subscription_key=key)
    all_lines = read_lines()
    langs = sys.argv[1:] or list(VOICES)
    cues = {}
    with tempfile.TemporaryDirectory() as d:
        for lang in langs:
            print(f"{lang}: {len(all_lines[lang])} lines")
            cues[lang] = build(client, lang, all_lines[lang], Path(d))
    write_cues(cues)
    print("wrote", ", ".join(f"public/audio/call-{l}.mp3" for l in langs), "and call-audio.ts")


if __name__ == "__main__":
    main()
