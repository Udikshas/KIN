"""Generate Kin's opening lines for every language and time of day, once.

Writes app/greetings.py. English lines are written by hand below; the other
languages are translated with Sarvam (mayura:v1, formal, female speaker) and
checked so every {name} / {family} placeholder survives exactly once. A line
that fails both translation modes falls back to English instead of shipping
broken text. Re-run only when the English lines change:

    .venv/bin/python scripts/generate_greetings.py
"""

import json
import os
import re
import sys
from pathlib import Path

from sarvamai import SarvamAI

API = Path(__file__).resolve().parents[1]
OUT = API / "app" / "greetings.py"

LANGS = {  # Sarvam LanguageName -> translate code
    "Hindi": "hi-IN", "Bengali": "bn-IN", "Tamil": "ta-IN", "Telugu": "te-IN", "Kannada": "kn-IN",
    "Malayalam": "ml-IN", "Marathi": "mr-IN", "Gujarati": "gu-IN", "Punjabi": "pa-IN", "Odia": "od-IN",
}
CHAT = {
    "morning": "a short morning chat",
    "afternoon": "a short afternoon chat",
    "evening": "a short evening chat",
    "night": "a short chat before bedtime",
}
SALUTE = {"morning": "Good morning", "afternoon": "Good afternoon", "evening": "Good evening", "night": "Good evening"}

# English source lines. {name} and {family} are filled per call.
ENGLISH = {
    **{f"outbound_{t}": f"{SALUTE[t]}, {{name}}. This is Kin, calling on behalf of {{family}} for {CHAT[t]}. Do you have a few minutes to talk?" for t in CHAT},
    "inbound_known": "Namaste {name}, this is Kin. It is so nice that you called. How are you?",
    "inbound_unknown": "Namaste, this is Kin. May I know who is calling?",
}
# Hindi is Kin's main language, so its lines are written by hand: the translator
# picks masculine verb forms ("bol raha hoon"), but Kin's voice is female.
HINDI_CHAT = {
    "morning": "सुबह की छोटी-सी बातचीत",
    "afternoon": "दोपहर की छोटी-सी बातचीत",
    "evening": "शाम की छोटी-सी बातचीत",
    "night": "सोने से पहले की छोटी-सी बातचीत",
}
HINDI = {
    **{f"outbound_{t}": f"नमस्ते {{name}}, मैं Kin बोल रही हूँ, {{family}} की तरफ़ से {HINDI_CHAT[t]} के लिए फ़ोन किया है। क्या अभी कुछ मिनट बात हो सकती है?" for t in CHAT},
    "inbound_known": "नमस्ते {name}, मैं Kin बोल रही हूँ। आपने फ़ोन किया, बहुत अच्छा लगा। बताइए, सब ठीक है?",
    "inbound_unknown": "नमस्ते, मैं Kin बोल रही हूँ। आप कौन बोल रहे हैं?",
}
# What gets translated: Indian languages open with Namaste rather than "Good morning".
SOURCE = {
    **{f"outbound_{t}": f"Namaste {{name}}, this is Kin, calling on behalf of {{family}} for {CHAT[t]}. Do you have a few minutes to talk?" for t in CHAT},
    "inbound_known": ENGLISH["inbound_known"],
    "inbound_unknown": ENGLISH["inbound_unknown"],
}


def placeholders_ok(src: str, out: str) -> bool:
    return all(out.count(p) == 1 for p in re.findall(r"\{\w+\}", src)) and "{" not in re.sub(r"\{\w+\}", "", out)


def main() -> None:
    for line in (API / ".env").read_text().splitlines():
        if line.startswith("SARVAM_API_KEY="):
            os.environ.setdefault("SARVAM_API_KEY", line.split("=", 1)[1].strip())
    if not os.environ.get("SARVAM_API_KEY"):
        sys.exit("SARVAM_API_KEY is empty in apps/api/.env")
    client = SarvamAI(api_subscription_key=os.environ["SARVAM_API_KEY"])

    table: dict[str, dict[str, str]] = {"English": dict(ENGLISH), "Hindi": dict(HINDI)}
    fallbacks = []
    for lang, code in LANGS.items():
        if lang in table:
            continue
        table[lang] = {}
        for key, src in SOURCE.items():
            text = None
            for mode in ("formal", "classic-colloquial"):
                res = client.text.translate(
                    input=src, source_language_code="en-IN", target_language_code=code,
                    speaker_gender="Female", mode=mode, model="mayura:v1",
                )
                if placeholders_ok(src, res.translated_text):
                    text = res.translated_text.strip()
                    break
            if text is None:
                text = ENGLISH[key]
                fallbacks.append(f"{lang}/{key}")
            table[lang][key] = text
        print(f"{lang}: done")

    OUT.write_text(
        '"""Generated by scripts/generate_greetings.py. Do not edit by hand.\n\n'
        "GREETINGS[language][kind] with kind in outbound_<morning|afternoon|evening|night>,\n"
        'inbound_known, inbound_unknown. Fill {name} and {family} with str.format.\n"""\n\n'
        f"GREETINGS: dict[str, dict[str, str]] = {json.dumps(table, ensure_ascii=False, indent=4)}\n"
    )
    print("wrote", OUT.relative_to(API), "| English fallbacks:", fallbacks or "none")


if __name__ == "__main__":
    main()
